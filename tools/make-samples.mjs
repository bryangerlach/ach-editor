function rec(kind, values = {}) {
  const record = ACH.createRecord(kind);
  Object.assign(record.fields, values);
  return record;
}

function entry(values, addenda = []) {
  return {
    detail: rec('entryDetail', {
      transactionCode: '22',
      identificationNumber: '',
      individualName: '',
      discretionaryData: '',
      ...values
    }),
    addenda
  };
}

